//! A stub Omarchy desk (lifted from `tests/omarchy.rs`): `<config>/omarchy` and stub
//! `omarchy-*` tools that log their argv and `OMARCHY_PATH` to `<root>/tools.log`.
//! omaddons runs with `PATH` holding the stubs alone, so the real tools (whose
//! `omarchy-bar put` would place the widget on this machine's bar) are never reachable;
//! the stubs use shell builtins, and coreutils by their absolute paths. `omarchy install`
//! adds the widget from a local export of its repository ([`write_widget_repo`]), never
//! from the network.

use std::fs;
use std::path::{Path, PathBuf};

use super::env::TestEnv;
use super::exec::write_executable;
use super::home::{Home, Run};

/// The bar widget's plugin id.
pub const WIDGET_ID: &str = "a44.omaddons";

/// Every stub tool a desk puts on `PATH`.
pub const TOOLS: [&str; 5] = [
    "omarchy-shell",
    "omarchy-plugin-validate",
    "omarchy-bar",
    "omarchy-plugin-disable",
    "omarchy-plugin-add",
];

/// The variable that points `omarchy install` at a local export of the widget.
pub const WIDGET_REPO_ENV: &str = "OMADDONS_WIDGET_REPO";

/// Writes a local export of the widget's repository into `dir`, as a clone holds it: the
/// runtime files of `omarchy/` (its tests aside) and a `.git`.
pub fn write_widget_repo(dir: &Path) {
    fn copy(from: &Path, to: &Path) {
        fs::create_dir_all(to).unwrap();
        for entry in fs::read_dir(from).unwrap() {
            let entry = entry.unwrap();
            let (path, name) = (entry.path(), entry.file_name());
            if path.is_dir() {
                if name != "tests" {
                    copy(&path, &to.join(&name));
                }
            } else {
                fs::copy(&path, to.join(&name)).unwrap();
            }
        }
    }
    if dir.join("manifest.json").is_file() {
        return;
    }
    copy(&Path::new(env!("CARGO_MANIFEST_DIR")).join("omarchy"), dir);
    fs::create_dir_all(dir.join(".git/objects")).unwrap();
    fs::create_dir_all(dir.join(".git/refs/heads")).unwrap();
    fs::write(dir.join(".git/HEAD"), "ref: refs/heads/main\n").unwrap();
    fs::write(
        dir.join(".git/refs/heads/main"),
        format!("{WIDGET_COMMIT}\n"),
    )
    .unwrap();
}

/// The commit [`write_widget_repo`]'s `main` names.
pub const WIDGET_COMMIT: &str = "c0ffee0123456789abcdef0123456789abcdef01";

/// A widget an older omaddons rendered into `dir`, as 0.2 wrote it (this build's version,
/// as a rebuild of it would carry): the manifest's entry points in `r-0123456789abcdef/`,
/// its `Build.js` recording `binary` and `context` (a `CONTEXT` JSON object), and
/// placeholders for the code. It validates.
pub fn plant_rendered(dir: &Path, binary: &Path, context: &str) {
    let code = dir.join("r-0123456789abcdef");
    fs::create_dir_all(&code).unwrap();
    fs::write(
        dir.join("manifest.json"),
        format!(
            r#"{{"schemaVersion": 1, "id": "{WIDGET_ID}", "name": "omaddons", "version": "{}", "kinds": ["service", "bar-widget"], "entryPoints": {{"service": "r-0123456789abcdef/Service.qml", "barWidget": "r-0123456789abcdef/BarWidget.qml"}}, "barWidget": {{"defaultSection": "right"}}}}"#,
            env!("CARGO_PKG_VERSION")
        ),
    )
    .unwrap();
    fs::write(code.join("Service.qml"), "Item {}\n").unwrap();
    fs::write(code.join("BarWidget.qml"), "Item {}\n").unwrap();
    fs::write(
        code.join("Build.js"),
        format!(
            ".pragma library\n\n// Generated by omaddons at install; never edited, never committed.\nvar BINARY = {}\nvar TOOL_VERSION = \"0.2.1\"\nvar PLUGIN_ID = \"{WIDGET_ID}\"\nvar CONTEXT = {context}\nvar CACHE_DIR = \"/nowhere\"\nvar CONTENT_SHA256 = \"{}\"\n",
            serde_json::Value::String(binary.display().to_string()),
            "0".repeat(64)
        ),
    )
    .unwrap();
}

/// The `CONTEXT` JSON of `env`'s run: its home and the four XDG directories.
pub fn context_json(env: &TestEnv) -> String {
    serde_json::json!({
        "HOME": env.home(),
        "XDG_CONFIG_HOME": env.config(),
        "XDG_STATE_HOME": env.state(),
        "XDG_CACHE_HOME": env.cache(),
        "XDG_DATA_HOME": env.data(),
    })
    .to_string()
}

/// Writes the stub tool `name` into `<root>/bin/`. `omarchy-bar` answers as
/// `<root>/bar-mode` says (`ok`, `not-running`, `unknown:<n>` for n "not a known widget"
/// answers first) and, placing, writes the section into `shell.json` as Omarchy's shell
/// would; `omarchy-plugin-validate` refuses when `<root>/validate-mode` says `bad`.
/// `omarchy-shell` answers `shell ping` as `<root>/shell-mode` says (`ok`, `silent` for
/// `-q`'s bare exit 0, `hang`, `orphan` for a hang that leaves a child running, its pid in
/// `<root>/orphan.pid`), and `setPluginEnabled`, like `omarchy-plugin-disable` (which
/// fails when `<root>/disable-mode` says `fail`), splices the bar layout out of
/// `shell.json`; `<id> state` answers as the widget's IPC does, its `session` the JSON in
/// `<root>/session` (none without it, as an older widget answers).
pub fn write_tool(at: &Path, name: &str) {
    let root = at.display();
    let log = format!(
        r#"printf '%s %s\n' "${{0##*/}}" "$*" >> {root}/tools.log
printf 'OMARCHY_PATH=%s\n' "$OMARCHY_PATH" >> {root}/tools.log"#
    );
    let body = match name {
        "omarchy-bar" => format!(
            r#"mode=ok; [ -f {root}/bar-mode ] && read mode < {root}/bar-mode
case "$mode" in
  not-running) echo "omarchy-shell is not running" >&2; exit 0 ;;
  unknown:*)
    n=0; [ -f {root}/bar-count ] && read n < {root}/bar-count; n=$((n+1)); echo $n > {root}/bar-count
    if [ $n -le "${{mode#unknown:}}" ]; then echo "$2 is not a known widget" >&2; exit 1; fi ;;
esac
printf '{{"bar":{{"layout":{{"%s":[{{"id":"%s"}}]}}}}}}' "$4" "$2" > "$XDG_CONFIG_HOME/omarchy/shell.json"
echo "$2 is on the bar""#
        ),
        "omarchy-plugin-validate" => format!(
            r#"mode=ok; [ -f {root}/validate-mode ] && read mode < {root}/validate-mode
if [ "$mode" = bad ]; then echo "manifest.json: entryPoints.barWidget is missing" >&2; exit 1; fi"#
        ),
        "omarchy-shell" => format!(
            r#"mode=ok; [ -f {root}/shell-mode ] && read mode < {root}/shell-mode
case "$1 $2" in
  "shell ping") case "$mode" in
      silent) exit 0 ;;
      hang) exec /bin/sleep 5 ;;
      orphan) /bin/sleep 30 & echo $! > {root}/orphan.pid; exec /bin/sleep 5 ;;
      daemon) /bin/sleep 30 & echo $! > {root}/orphan.pid ;;
    esac; echo ok ;;
  "shell setPluginEnabled")
    printf '{{"bar":{{"layout":{{}}}}}}' > "$XDG_CONFIG_HOME/omarchy/shell.json"; echo ok ;;
  *" state")
    if [ -f {root}/session ]; then IFS= read -r s < {root}/session; printf '{{"phase":"idle","session":%s}}\n' "$s"
    else echo '{{"phase":"idle"}}'; fi ;;
esac"#
        ),
        // As Omarchy's own: the id from the repository's manifest, refused when a folder
        // already has that name or another plugin folder's manifest names it; then the
        // copy (its clone) moved into place. `<root>/add-mode` says `fail` (the clone
        // fails) or `late-fail` (it fails after the move, as a failed rescan would).
        "omarchy-plugin-add" => format!(
            r#"mode=ok; [ -f {root}/add-mode ] && read mode < {root}/add-mode
if [ "$mode" = fail ]; then echo "omarchy-plugin-add: failed to clone $1" >&2; exit 1; fi
plugins="$XDG_CONFIG_HOME/omarchy/plugins"
id=$(/bin/sed -n 's/.*"id": *"\([^"]*\)".*/\1/p' "$1/manifest.json" | /bin/head -n 1)
if [ -z "$id" ]; then echo "omarchy-plugin-add: refusing to add: validation failed" >&2; exit 1; fi
if [ -e "$plugins/$id" ] || [ -L "$plugins/$id" ]; then
  echo "omarchy-plugin-add: plugin '$id' is already installed; update it with: omarchy plugin update $id" >&2; exit 1
fi
for d in "$plugins"/*/; do
  if [ -f "$d/manifest.json" ] && /bin/grep -q "\"id\": *\"$id\"" "$d/manifest.json"; then
    echo "omarchy-plugin-add: plugin id '$id' is already used by ${{d}}manifest.json" >&2; exit 1
  fi
done
/bin/mkdir -p "$plugins" && /bin/cp -r "$1" "$plugins/.add.tmp.$$" && /bin/mv "$plugins/.add.tmp.$$" "$plugins/$id"
echo "Added $id into $plugins/$id"
if [ "$mode" = late-fail ]; then echo "omarchy-shell: could not reach the shell" >&2; exit 1; fi"#
        ),
        "omarchy-plugin-disable" => format!(
            r#"mode=ok; [ -f {root}/disable-mode ] && read mode < {root}/disable-mode
if [ "$mode" = fail ]; then echo "omarchy-plugin-disable: plugin '$1' is not known" >&2; exit 1; fi
printf '{{"bar":{{"layout":{{}}}}}}' > "$XDG_CONFIG_HOME/omarchy/shell.json"
echo "Disabled $1""#
        ),
        _ => String::new(),
    };
    let path = at.join("bin").join(name);
    write_executable(&path, &format!("#!/bin/sh\n{log}\n{body}\n"));
}

/// A stub desk in a test environment: `<config>/omarchy`, every stub tool in
/// `<root>/bin/`, and `<root>/omarchy/shell/`, so a run given only [`StubDesk::omarchy_path`]
/// as `OMARCHY_PATH` (a doctor or `status` run, which starts no Omarchy tool) finds
/// Omarchy's shell installed too.
pub struct StubDesk {
    root: PathBuf,
    config: PathBuf,
}

/// The stub desk of `env`, written on first use (writing it again changes nothing).
pub fn stub_desk(env: &TestEnv) -> StubDesk {
    let desk = StubDesk {
        root: env.root().to_path_buf(),
        config: env.config(),
    };
    fs::create_dir_all(desk.config.join("omarchy")).unwrap();
    fs::create_dir_all(desk.root.join("bin")).unwrap();
    fs::create_dir_all(desk.omarchy_path().join("shell")).unwrap();
    for tool in TOOLS {
        write_tool(&desk.root, tool);
    }
    write_widget_repo(&desk.widget_repo());
    desk
}

impl StubDesk {
    /// `<root>/bin`, the stubs: the whole `PATH` of a run that may start Omarchy's tools.
    pub fn bin(&self) -> PathBuf {
        self.root.join("bin")
    }

    /// `<root>/omarchy`, the run's `OMARCHY_PATH` (`common::doctor::plant::omarchy_path`).
    pub fn omarchy_path(&self) -> PathBuf {
        self.root.join("omarchy")
    }

    /// `<config>/omarchy/plugins/a44.omaddons`, where `omarchy install` puts the widget.
    pub fn plugin(&self) -> PathBuf {
        self.config.join("omarchy/plugins/a44.omaddons")
    }

    /// `<root>/widget-repo`, the local export `omarchy install` adds the widget from.
    pub fn widget_repo(&self) -> PathBuf {
        self.root.join("widget-repo")
    }

    /// The environment of a run that may start Omarchy's tools: `PATH` holding the stubs
    /// alone, `OMARCHY_PATH`, and the local export of the widget.
    pub fn env(&self) -> [(&'static str, PathBuf); 3] {
        [
            ("PATH", self.bin()),
            ("OMARCHY_PATH", self.omarchy_path()),
            (WIDGET_REPO_ENV, self.widget_repo()),
        ]
    }

    /// `omaddons omarchy install --json` on `home` with the stubs: the widget's checkout,
    /// added from the local export through the `omarchy-plugin-add` stub. Asserts exit 0.
    pub fn install(&self, home: &Home) -> Run {
        let env = self.env();
        let extra: Vec<(&str, &str)> = env
            .iter()
            .map(|(key, value)| (*key, value.to_str().unwrap()))
            .collect();
        let args = ["omarchy", "install", "--json"].map(str::to_owned);
        let run = home.exec_with(&args, &extra);
        assert_eq!(run.code, 0, "omarchy install\n{}", run.context());
        run
    }
}
