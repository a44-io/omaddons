    fn read_existing_reads_no_more_than_it_needs() {
        let tmp = tempfile::tempdir().unwrap();
        let dir = tmp.path();
        let script = marked_script(Shell::Bash).unwrap();
        let file = dir.join("omaddons");
        let read = |path: &Path| read_existing(path, &script).unwrap();
        assert_eq!(read(&file), Existing::Missing);
        std::fs::write(&file, &script).unwrap();
        assert_eq!(
            read(&file),
            Existing::File {
                ours: true,
                same: true
            }
        );
        let mut older = script.clone();
        older.extend_from_slice(b"# an older build's line\n");
        std::fs::write(&file, &older).unwrap();
        assert_eq!(
            read(&file),
            Existing::File {
                ours: true,
                same: false
            }
        );
        let mut edited = script.clone();
        let last = edited.len() - 2;
        edited[last] ^= 0x01;
        std::fs::write(&file, &edited).unwrap();
        assert_eq!(
            read(&file),
            Existing::File {
                ours: true,
                same: false
            },
            "the same length, other bytes"
        );
        std::fs::write(&file, b"complete -F _mine omaddons\n").unwrap();
        assert_eq!(
            read(&file),
            Existing::File {
                ours: false,
                same: false
            }
        );
        let link = dir.join("link");
        std::os::unix::fs::symlink(&file, &link).unwrap();
        assert_eq!(
            read(&link),
            Existing::Symlink {
                link_target: file.clone()
            },
            "never read through"
        );
        assert_eq!(read(dir), Existing::NotAFile);
    }

