    #[test]
    fn data_serializes_in_order_with_closed_written_values() {
        let json = serde_json::to_string(outcome(Shell::Bash, false, Written::Fresh, true).data())
            .unwrap();
        assert_eq!(
            json,
            "{\"dry_run\":false,\"shell\":\"bash\",\"file\":\"/h/.local/share/bash-completion/completions/omaddons\",\"written\":\"fresh\",\"bytes\":61440,\"dir_created\":true}"
        );
        let schema = serde_json::to_value(schemars::schema_for!(Written)).unwrap();
        let consts: Vec<&serde_json::Value> = schema["oneOf"]
            .as_array()
            .into_iter()
            .flatten()
            .map(|variant| &variant["const"])
            .collect();
        assert_eq!(
            consts,
            [
                &serde_json::json!("fresh"),
                &serde_json::json!("replaced"),
                &serde_json::json!("unchanged")
            ],
            "a closed enum of exactly these values: {schema}"
        );
    }

    #[test]
    fn human_output_for_each_outcome() {
        let bash = "/h/.local/share/bash-completion/completions/omaddons";
        let zsh = "/h/.zfunc/_omaddons";
        let fpath =
            "  add fpath+=(\"$HOME/.zfunc\") to .zshrc before compinit, then start a new shell";
        let new_shell = "  start a new shell to use it";
        for (case, outcome, want) in [
            (
                "fresh",
                outcome(Shell::Bash, false, Written::Fresh, true),
                vec![
                    format!("installed the bash completion script: {bash} (61,440 bytes)"),
                    new_shell.to_owned(),
                ],
            ),
            (
                "replaced",
                outcome(Shell::Bash, false, Written::Replaced, false),
                vec![
                    format!("updated the bash completion script: {bash} (61,440 bytes)"),
                    new_shell.to_owned(),
                ],
            ),
            (
                "unchanged",
                outcome(Shell::Bash, false, Written::Unchanged, false),
                vec![format!("the bash completion script is up to date: {bash}")],
            ),
            (
                "dry_run_fresh",
                outcome(Shell::Bash, true, Written::Fresh, true),
                vec![format!(
                    "would install the bash completion script: {bash} (61,440 bytes)"
                )],
            ),
            (
                "dry_run_replaced",
                outcome(Shell::Bash, true, Written::Replaced, false),
                vec![format!(
                    "would update the bash completion script: {bash} (61,440 bytes)"
                )],
            ),
            (
                "zsh_fresh_creating_zfunc",
                outcome(Shell::Zsh, false, Written::Fresh, true),
                vec![
                    format!("installed the zsh completion script: {zsh} (61,440 bytes)"),
                    fpath.to_owned(),
                ],
            ),
            (
                "zsh_dry_run_creating_zfunc",
                outcome(Shell::Zsh, true, Written::Fresh, true),
                vec![
                    format!("would install the zsh completion script: {zsh} (61,440 bytes)"),
                    fpath.to_owned(),
                ],
            ),
            (
                "zsh_fresh_into_an_existing_zfunc",
                outcome(Shell::Zsh, false, Written::Fresh, false),
                vec![
                    format!("installed the zsh completion script: {zsh} (61,440 bytes)"),
                    new_shell.to_owned(),
                ],
            ),
        ] {
            let mut out = Vec::new();
            outcome.render_human(&mut out, &Style::default()).unwrap();
            let got = String::from_utf8(out).unwrap();
            assert_eq!(got.lines().collect::<Vec<_>>(), want, "{case}:\n{got}");
        }
    }
