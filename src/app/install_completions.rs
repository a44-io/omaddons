    #[test]
    fn locations_follow_the_xdg_folders() {
        let paths = Paths::from_lookup(|name| match name {
            "HOME" => Some("/h".into()),
            "XDG_DATA_HOME" => Some("/d".into()),
            "XDG_CONFIG_HOME" => Some("/c".into()),
            _ => None,
        })
        .unwrap();
        for (shell, file, base) in [
            (Shell::Bash, "/d/bash-completion/completions/omaddons", "/d"),
            (Shell::Zsh, "/h/.zfunc/_omaddons", "/h"),
            (Shell::Fish, "/c/fish/completions/omaddons.fish", "/c"),
        ] {
            assert_eq!(
                location(&paths, shell).unwrap(),
                (PathBuf::from(file), PathBuf::from(base)),
                "{shell:?}"
            );
        }
        let defaults = Paths::from_lookup(|name| (name == "HOME").then(|| "/h".into())).unwrap();
        assert_eq!(
            location(&defaults, Shell::Bash).unwrap().0,
            PathBuf::from("/h/.local/share/bash-completion/completions/omaddons")
        );
        assert_eq!(
            location(&defaults, Shell::Fish).unwrap().0,
            PathBuf::from("/h/.config/fish/completions/omaddons.fish")
        );
    }

