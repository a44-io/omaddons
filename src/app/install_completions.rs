//! `omaddons install-completions <SHELL> [--force]`: the script `completions <SHELL>`
//! prints, with a marker line, written where the shell looks for a user's completions:
//!
//! - bash: `<data>/bash-completion/completions/omaddons`, which bash-completion loads on
//!   the first Tab;
//! - zsh: `<home>/.zfunc/_omaddons`, which `compinit` autoloads once `.zfunc` is on
//!   `fpath` (the output says so when the run creates `.zfunc`);
//! - fish: `<config>/fish/completions/omaddons.fish`, loaded on first use.
//!
//! elvish and PowerShell load completions from their rc files, which omaddons never edits:
//! they are `usage`. `completions` itself stays pure and keeps its facts; this is a command
//! of its own because a writing flag would make `completions` a mutating command.
//!
//! It writes through fsx as `Writer::Completions`, into that one file and the folders
//! missing below the shell's base (the scope `ScopeTable::with_completion_file` builds),
//! never through a symlink. A file whose first line (its second, after zsh's
//! `#compdef omaddons`) is not the marker is someone else's: it is refused with
//! `file_exists` unless `--force` is given. A fresh file is published without replacing
//! one another program created meanwhile, and a replaced one only while it is still the
//! file the run read (its inode and mode), so two runs at once never clobber each other.
//!
//! Like `backup export`, it writes a file of the user's own and nothing of omaddons': no
//! history line (a new history kind is a persisted-format change of `history.jsonl` and
//! the folder journal, for a record nothing reads), no global lock, no recovery, and no
//! doorbell (`status` reports nothing about it). It neither stores a plan nor binds
//! (M4-D22), as `robot-docs install-skill` does not: the bytes come from the binary, the
//! destination from the environment, and the one outside input, the file already there,
//! is guarded at the write itself.

