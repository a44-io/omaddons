// The plan scenes for the QML tests (pipeline step 4): every `plan-*.json` envelope the
// real binary wrote in step 1, as a QML JavaScript resource `tst_plans.qml` imports.
// Each envelope's `tool_version` becomes the fixture Build.js's, so Model.compatible
// accepts it under that Build.js; nothing else changes.
//
// Usage: bun omarchy/tests/qml_fixtures.js <fixtures dir> <out file>
// The pipeline writes <out file> into its temporary copy of the plugin only: never a
// tracked file.

const fs = require("fs")
const path = require("path")

const [fixtures, out] = process.argv.slice(2)
if (!fixtures || !out) {
  console.error("usage: bun omarchy/tests/qml_fixtures.js <fixtures dir> <out file>")
  process.exit(2)
}

const build = fs.readFileSync(path.join(__dirname, "fixtures", "Build.js"), "utf8")
const version = (build.match(/^var TOOL_VERSION = "([^"]+)"$/m) || [])[1]
if (!version) throw new Error("the fixture Build.js has no TOOL_VERSION")

const text = {}
for (const file of fs.readdirSync(fixtures).sort()) {
  if (!file.startsWith("plan-") || !file.endsWith(".json")) continue
  const envelope = JSON.parse(fs.readFileSync(path.join(fixtures, file), "utf8"))
  envelope.tool_version = version
  text[file.slice(0, -".json".length)] = JSON.stringify(envelope)
}
if (Object.keys(text).length === 0) throw new Error("no plan-*.json in " + fixtures + ": run step 1 first")

const lines = [
  ".pragma library",
  "",
  "// Generated by omarchy/tests/qml_fixtures.js from the envelopes the binary wrote; never committed.",
  "var TEXT = " + JSON.stringify(text, null, 1),
  "",
  "// The envelope fixture `name` as the binary printed it (one line).",
  "function text(name) {",
  "  if (!TEXT.hasOwnProperty(name)) throw new Error(\"no plan fixture \" + name)",
  "  return TEXT[name]",
  "}",
  "",
]
fs.writeFileSync(out, lines.join("\n"))
