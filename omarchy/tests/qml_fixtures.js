// The envelope scenes for the QML tests (pipeline step 4): every `*.json` envelope the
// real binary wrote in step 1 (the contract dumps aside), as a QML JavaScript resource
// `tst_plans.qml` and `tst_snapshots.qml` import. Each envelope's `tool_version` becomes
// the fixture Build.js's, so Model.compatible accepts it under that Build.js; nothing
// else changes. The optional third argument is where tst_snapshots.qml saves its PNGs
// (empty: it renders and checks them, and saves nothing).
//
// Usage: bun omarchy/tests/qml_fixtures.js <fixtures dir> <out file> [<snapshot dir>]
// The pipeline writes <out file> into its temporary copy of the plugin only: never a
// tracked file.

const fs = require("fs")
const path = require("path")

const [fixtures, out, snapshots] = process.argv.slice(2)
if (!fixtures || !out) {
  console.error("usage: bun omarchy/tests/qml_fixtures.js <fixtures dir> <out file> [<snapshot dir>]")
  process.exit(2)
}

const build = fs.readFileSync(path.join(__dirname, "fixtures", "Build.js"), "utf8")
const version = (build.match(/^var TOOL_VERSION = "([^"]+)"$/m) || [])[1]
if (!version) throw new Error("the fixture Build.js has no TOOL_VERSION")

const text = {}
for (const file of fs.readdirSync(fixtures).sort()) {
  if (!file.endsWith(".json") || file.startsWith("contract-")) continue
  const envelope = JSON.parse(fs.readFileSync(path.join(fixtures, file), "utf8"))
  // An envelope only: `repair-context` and `repair-argv` are plain data.
  if (typeof envelope.ok === "boolean") envelope.tool_version = version
  text[file.slice(0, -".json".length)] = JSON.stringify(envelope)
}
if (!Object.keys(text).some((name) => name.startsWith("plan-"))) throw new Error("no plan-*.json in " + fixtures + ": run step 1 first")

const lines = [
  ".pragma library",
  "",
  "// Generated by omarchy/tests/qml_fixtures.js from the envelopes the binary wrote; never committed.",
  "var TEXT = " + JSON.stringify(text, null, 1),
  "",
  "// Where tst_snapshots.qml saves its renders; empty saves none.",
  "var SNAPSHOT_DIR = " + JSON.stringify(snapshots ? path.resolve(snapshots) : ""),
  "",
  "// The envelope fixture `name` as the binary printed it (one line).",
  "function text(name) {",
  "  if (!TEXT.hasOwnProperty(name)) throw new Error(\"no fixture \" + name)",
  "  return TEXT[name]",
  "}",
  "",
]
fs.writeFileSync(out, lines.join("\n"))
